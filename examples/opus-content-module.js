import {
  createBlueFissionApp,
  createCrudPanelModule,
  createJQueryBridge,
  createRecordModel
} from "../src/index.js";

const app = createBlueFissionApp({
  apiBaseUrl: "/api",
  resources: {
    content: "admin/content"
  }
});

const bridge = createJQueryBridge(window.jQuery);

const content = createRecordModel({
  content_id: 0,
  title: "",
  slug: "",
  uri: "",
  keywords: "",
  description: "",
  is_published: 0,
  is_autogenerated: 0,
  body: "",
  template: ""
});

const contentModule = createCrudPanelModule({
  name: "content",
  resource: app.resources.content,
  model: content,
  bridge,
  ui: {
    notice(message, type) {
      console.log(type || "success", message);
    }
  },
  screens: {
    list: "#content-listing-screen",
    edit: "#content-edit-screen"
  },
  selectors: {
    homeButton: ".home-btn",
    addButton: "#content-add-btn",
    saveButton: "#content-save-btn",
    deleteButton: "#content-delete-btn",
    showButton: ".show-btn",
    editButton: ".edit-btn"
  },
  list: {
    root: "#dataTable",
    selector: "#dataTable",
    getRecord(trigger) {
      return window.contentTable.row(window.jQuery(trigger).parents("tr")).data();
    }
  },
  messages: {
    saved: "Content has been saved.",
    deleted: "Content has been deleted."
  }
});

app.start(contentModule);
